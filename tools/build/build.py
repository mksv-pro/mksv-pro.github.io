def plain_logos():
    """The places worked and studied at, as a row of logos in the banner: each once, experience first."""
    def height(f):
        """rem: the same visual weight for wide wordmarks and square marks (height ~ aspect^-0.4), capped."""
        w, h = struct.unpack(">II", (PUBLIC / "assets/img/logos" / f).read_bytes()[16:24])  # (PNG IHDR)
        return min(2.2, max(1.1, 1.6 * (3 * h / w) ** 0.4))

    school = {x["logo"]: x["school"] for x in DATA["education"] if x.get("logo")}  # (a logo's name: its school's, if any)
    seen = {}
    for e in DATA["experience"] + DATA["education"]:
        if e.get("logo") and e["logo"] not in seen:
            seen[e["logo"]] = re.sub(r"<[^>]+>", "", school.get(e["logo"]) or e.get("cv_org") or e["org"])
    imgs = "".join(f'<img src="{{{{root}}}}assets/img/logos/{f}" alt="{escape(alt)}" style="height:{height(f):.2f}rem">' for f, alt in seen.items())
    return f'    <div class="logos">{imgs}</div>' if imgs else ""


def plain_body():
    """Each thing once: an experience carries the work done there and its report (links); the other
    work as projects; degrees in the opening paragraph."""
    pub_of = {p["work"]: p for p in DATA["publications"] if p.get("work")}
    work_at = {p["at"]: p for p in DATA["work"] if p.get("at")}

    def links(work, own=()):
        pub = pub_of.get((work or {}).get("id"))
        bib = [{"label": "bib", "href": f'{{{{root}}}}assets/bib/{pub["bib"]}'}] if pub and pub.get("bib") else []
        return " &middot; ".join(f'<a href="{a["href"]}">{re.sub(r"<[^>]+>", "", a["label"]).split()[0]}</a>'
                                 for a in (work or {}).get("actions", []) + list(own) + bib)

    def post(role, sentence):
        """'research intern with A &amp; B'; who with only when the sentence already names the post."""
        head, _, rest = (re.split(r"( · | &middot; )", role, maxsplit=1) + ["", ""])[:3]
        if head and re.sub(r"<[^>]+>", "", sentence).lower().startswith(head.lower()):
            return rest
        return f"{head[:1].lower()}{head[1:]} {rest}".strip()

    def section(key, title, items):
        return (f'        <section id="{key}">\n          <h2>{title}</h2>\n          <ul class="entries">\n'
                + "\n".join(items) + "\n          </ul>\n        </section>") if items else ""

    body = [plain_studies()]
    body.append(section("experience", "Experience", [
        plain_entry(f'<b>{e["org"]}</b>, {post(e.get("role", ""), first_sentence(e.get("cv_text") or e.get("text", "")))}, {span(e["from"], e.get("to"))}',
                    first_sentence(e.get("cv_text") or e.get("text", "")), links(work_at.get(e.get("arms")), e.get("actions", [])))
        for e in DATA["experience"]]))
    body.append(section("projects", "Projects", [
        plain_entry(f'<b>{p["title"]}</b>, {p["role"][0].lower()}{re.sub(r" · | &middot; ", ", ", p["role"])[1:]}, {when(p["date"])}',
                    first_sentence(p.get("cv_text") or p["text"]), links(p))
        for p in DATA["work"] if not p.get("at")]))
    body.append(section("publications", "Publications", [
        plain_entry(f'<a href="{p["href"]}">{p["title"]}</a>', p["venue"] + ".", "")
        for p in DATA["publications"] if p.get("work") not in {w["id"] for w in DATA["work"]}]))
    for key, title in (("talks", "Talks"), ("teaching", "Teaching")):
        body.append(section(key, title, [plain_entry(f'<b>{e["title"]}</b>, {when(e["date"])}', e.get("venue", "") + ".", "")
                                         for e in DATA[key]]))
    main = "      <div class=\"text\">\n" + "\n".join(x for x in body if x) + "\n      </div>"
    return plain_side() + "\n" + main


