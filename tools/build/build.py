def plain_studies():
    """The opening paragraph: the programmes followed now, then the earlier degrees, each with its school."""
    s = DATA["site"]
    now = [x for x in DATA["education"] if x.get("now")]
    courses = plain_courses()

    def name(x):
        """The programme's name; a link that unfolds its courses, when they are listed."""
        t = x["degree"].removeprefix("MSc ")
        c = courses.get(DATA["education"].index(x))
        if c:
            return f'<a href="#{c[0]}" class="unfold" aria-controls="{c[0]}" aria-expanded="false">{t}</a>'
        return official(x, t)
    past = [x for x in DATA["education"] if not x.get("now") and not x.get("cv_skip")]
    join = lambda xs: ", ".join(xs[:-1]) + " and " + xs[-1] if len(xs) > 1 else xs[0]  # noqa: E731
    n = ("one", "two", "three", "four")[len(now) - 1] if 0 < len(now) <= 4 else str(len(now))
    out = f'I am a {s["role"][0].lower()}{s["role"][1:]} in {s["place"]}'
    if now:
        out += (f", following {n} master's programmes in parallel: " if len(now) > 1 else ", in the ") + join(
            [f'{name(x)} ({x["school"]})' for x in now]) + "."
    if past:
        out += " Before that: " + "; ".join(f'{official(x, x["degree"])} ({x["school"]}, {x["dates"]})' for x in past) + "."
    script = ("\n        <script>for (const a of document.querySelectorAll('a.unfold')) a.addEventListener('click', (e) => {"
              " e.preventDefault(); const b = document.getElementById(a.getAttribute('aria-controls'));"
              " b.hidden = !b.hidden; a.setAttribute('aria-expanded', String(!b.hidden)); });</script>") if courses else ""
    return f'        <p id="education">{out}</p>\n' + "\n".join(c for _, c in courses.values()) + script


def plain_courses():
    """The `on_about` programmes' courses, keyed by the degree they belong to (an `education` entry's
    position): {i: (anchor id, hidden block)}. Its name in the opening paragraph unfolds the block."""
    def initials(names):
        """'Christophe Texier, Fabio Pietrucci' -> 'C. Texier, F. Pietrucci'."""
        return ", ".join(f"{n[0]}. {n.split(' ', 1)[1]}" for n in names.split(", "))

    def line(c):
        return f'\n          <li>{c}</li>' if isinstance(c, str) else \
            f'\n          <li>{c["title"]} &ndash; <b>{initials(c["by"])}</b></li>'

    out = {}
    for e in DATA.get("coursework", []):
        if not e.get("on_about"):
            continue
        k = next(k for k, x in enumerate(DATA["education"]) if x.get("now") and x["school"] == e["school"]
                 and x["degree"] in e["programme"])
        ed = DATA["education"][k]
        y0, y1 = e["years"].split("\u2013")
        hid = f'courses-{ed.get("arms") or k}'
        out[k] = (hid, f'        <div class="courses" id="{hid}" hidden>\n'
                       f'          <p>{ed.get("about") or ed["degree"]}, courses {y0}\u2013{y1[2:]}</p>\n'
                       f'          <ul>{"".join(line(c) for c in e["courses"])}\n          </ul>\n        </div>')
    return out


