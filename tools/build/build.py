KANJI = "〇一二三四五六七八九"
SHINBUN_FIRST = datetime.date(2021, 9, 1)  # (issue 0: the first day of the physics degree)


def kanji_digits(n):
    """2026 -> 二〇二六 (digit by digit, as years and issue numbers are set)."""
    return "".join(KANJI[int(c)] for c in str(n))


def kanji_number(n):
    """1..99 -> 一 .. 九十九 (as months and days are set)."""
    tens, ones = divmod(n, 10)
    return ((KANJI[tens] if tens > 1 else "") + "十" if tens else "") + (KANJI[ones] if ones else "")


def shinbun_date():
    """The issue's date, in kanji: the month of the latest news here (the build stays the same from
    day to day); the page's script sets the reader's own day and the issue number over it."""
    y, m = map(int, (DATA.get("now") or DATA["news"][0])["date"].split("-"))
    return (f'<span class="issue">第{kanji_digits((datetime.date(y, m, 1) - SHINBUN_FIRST).days)}號</span>'
            f'<span class="day">{kanji_digits(y)}年{kanji_number(m)}月</span>')


